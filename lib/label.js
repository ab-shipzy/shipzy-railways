import PDFDocument from 'pdfkit';
import bwipjs from 'bwip-js';
import { loadData } from './storage';

export async function generateLabelPDF(shipmentId) {
  const data = loadData();
  const shipment = data.shipments.find(s => s.id === shipmentId);
  if (!shipment) throw new Error('Shipment not found');

  const customer = data.customers.find(c => c.id === shipment.customerId);
  const pickup = data.warehouses.find(w => w.id === shipment.pickupWarehouseId);
  const delivery = data.warehouses.find(w => w.id === shipment.deliveryWarehouseId);

  const doc = new PDFDocument({ size: [288, 432], margin: 10 }); // 4x6 inches

  const buffers = [];
  doc.on('data', buffers.push.bind(buffers));
  const pdfPromise = new Promise((resolve) => {
    doc.on('end', () => resolve(Buffer.concat(buffers)));
  });

  for (let i = 0; i < shipment.boxAWBs.length; i++) {
    if (i > 0) doc.addPage();
    const awb = shipment.boxAWBs[i];
    await drawLabelPage(doc, {
      awb,
      shipment,
      customer,
      pickup,
      delivery,
      boxIndex: i + 1,
      totalBoxes: shipment.boxAWBs.length,
    });
  }

  doc.end();
  return pdfPromise;
}

async function drawLabelPage(doc, { awb, shipment, customer, pickup, delivery, boxIndex, totalBoxes }) {
  try {
    const barcode = await bwipjs.toBuffer({
      bcid: 'code128',
      text: awb,
      scale: 2,
      height: 10,
      includetext: true,
      textxalign: 'center',
    });
    doc.image(barcode, 20, 15, { width: 250 });
  } catch (e) {
    doc.text(awb, 20, 20);
  }

  doc.fontSize(10).text(`${awb}`, 20, 70);
  doc.fontSize(8).text('SHIPZY RAILWAYS', 180, 70, { align: 'right' });

  doc.fontSize(9).text('Shipping Address', 20, 90, { underline: true });
  doc.fontSize(8).text(customer?.name || 'Customer', 20, 105);
  doc.text(delivery?.address || '', 20, 118);
  doc.text(`${delivery?.city || ''} - ${delivery?.pin || ''}`, 20, 130);

  doc.fontSize(10).text('Prepaid', 200, 100);

  doc.fontSize(8).text('Seller:', 20, 150);
  doc.text(pickup?.name || '', 50, 150);
  doc.text(pickup?.address || '', 20, 162);
  doc.text(`${pickup?.city || ''} ${pickup?.pin || ''}`, 20, 174);

  doc.text(`Order No: ${shipment.invoiceNumber || 'N/A'}`, 20, 195);
  doc.text(`Invoice Amt: ${shipment.invoiceAmount || 0}`, 20, 208);
  doc.text(`Insurance: ${shipment.insurance ? 'Yes' : 'No'}`, 150, 208);

  doc.text(`Product: ${shipment.productDescription || 'General Cargo'}`, 20, 225);
  doc.text(`Box ${boxIndex} of ${totalBoxes}`, 20, 238);

  try {
    const barcode2 = await bwipjs.toBuffer({
      bcid: 'code128',
      text: awb,
      scale: 1.5,
      height: 8,
    });
    doc.image(barcode2, 20, 260, { width: 200 });
  } catch (e) {}

  doc.fontSize(14).font('Helvetica-Bold').text('SHIPZY RAILWAYS', 20, 320, { align: 'center' });
  doc.fontSize(7).font('Helvetica').text('Label generated by Shipzy Railways', 20, 350, { align: 'center' });
}
