import PDFDocument from 'pdfkit';
import bwipjs from 'bwip-js';
import { getShipments, getWarehouses, getStations } from './db';

export async function generateLabelPDF(shipmentId) {
  const shipments = await getShipments();
  const warehouses = await getWarehouses();
  const stations = await getStations();

  const shipment = shipments.find(s => s.id === shipmentId);
  if (!shipment) throw new Error('Shipment not found');

  const pickup = warehouses.find(w => w.id === shipment.pickupWarehouseId) || {};
  const delivery = warehouses.find(w => w.id === shipment.deliveryWarehouseId) || {};
  const origin = stations.find(s => s.id === shipment.originStationId) || {};
  const dest = stations.find(s => s.id === shipment.destinationStationId) || {};

  const doc = new PDFDocument({ size: [288, 432], margin: 8 });

  const buffers = [];
  doc.on('data', chunk => buffers.push(chunk));
  const pdfPromise = new Promise(resolve => doc.on('end', () => resolve(Buffer.concat(buffers))));

  const masterAWB = shipment.masterAWB || '';
  const boxAWBs = shipment.boxAWBs || [];
  const bookedAt = shipment.createdAt ? new Date(shipment.createdAt) : new Date();

  for (let i = 0; i < boxAWBs.length; i++) {
    if (i > 0) doc.addPage();
    await drawLabelPage(doc, {
      childAWB: boxAWBs[i],
      masterAWB,
      shipment,
      pickup,
      delivery,
      origin,
      dest,
      boxIndex: i + 1,
      totalBoxes: boxAWBs.length,
      bookedAt,
    });
  }

  doc.end();
  return pdfPromise;
}

function formatAddress(w) {
  const lines = [];
  if (w.name) lines.push(w.name);
  if (w.address) lines.push(w.address);
  const cityLine = [w.city, w.state, w.pin].filter(Boolean).join(', ');
  if (cityLine) lines.push(cityLine);
  if (w.pocName || w.phone) lines.push([w.pocName, w.phone].filter(Boolean).join(' • '));
  return lines.join('\n');
}

function formatDateTime(d) {
  const pad = n => String(n).padStart(2, '0');
  return `${pad(d.getDate())}-${pad(d.getMonth() + 1)}-${d.getFullYear()} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

async function drawLabelPage(doc, { childAWB, masterAWB, shipment, pickup, delivery, origin, dest, boxIndex, totalBoxes, bookedAt }) {
  doc.rect(0, 0, 288, 26).fill('#0f172a');
  doc.fillColor('#ffffff').fontSize(9).font('Helvetica-Bold').text('SHIPZY RAILWAYS', 10, 8);
  doc.fontSize(7).font('Helvetica').text('4x6 Label', 200, 9, { align: 'right', width: 80 });

  doc.fillColor('#0f172a').fontSize(7).font('Helvetica-Bold').text('MASTER AWB', 12, 34);
  doc.fontSize(12).font('Helvetica-Bold').text(masterAWB || '—', 12, 44);
  doc.fontSize(6).font('Helvetica').fillColor('#64748b').text(`Booked: ${formatDateTime(bookedAt)}`, 140, 48, { align: 'right', width: 136 });

  doc.rect(8, 64, 272, 62).stroke('#cbd5e1');
  doc.fillColor('#0f172a').fontSize(6).font('Helvetica-Bold').text('SHIPPING ADDRESS', 14, 68);
  doc.font('Helvetica').fontSize(7).text(formatAddress(delivery) || 'Delivery hub not set', 14, 78, { width: 180, height: 44 });
  doc.rect(200, 68, 68, 14).fill('#10b981');
  doc.fillColor('#ffffff').fontSize(7).font('Helvetica-Bold').text('PREPAID', 210, 71);

  doc.fillColor('#0f172a').fontSize(6).font('Helvetica-Bold').text('CONSIGNOR', 14, 132);
  doc.font('Helvetica').fontSize(7).text(formatAddress(pickup) || 'Pickup hub not set', 14, 142, { width: 160, height: 32 });
  doc.fontSize(6).text(`Inv: ${shipment.invoiceNumber || 'N/A'}`, 180, 142);
  doc.text(`Amt: ${shipment.invoiceAmount || 0}`, 180, 152);

  doc.rect(8, 178, 272, 26).fill('#f1f5f9');
  doc.fillColor('#0f172a').fontSize(6).font('Helvetica-Bold').text('PRODUCT', 14, 182);
  doc.font('Helvetica').fontSize(6).text(shipment.productDescription || 'General Cargo', 14, 192, { width: 160 });
  doc.rect(200, 182, 68, 18).fill('#0074ff');
  doc.fillColor('#ffffff').fontSize(10).font('Helvetica-Bold').text(`${boxIndex}/${totalBoxes}`, 200, 186, { align: 'center', width: 68 });

  doc.rect(8, 210, 272, 28).stroke('#0074ff');
  doc.fillColor('#0074ff').fontSize(7).font('Helvetica-Bold').text('ORIGIN', 16, 214);
  doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text(origin.code || '—', 16, 224);
  doc.fillColor('#0074ff').fontSize(7).font('Helvetica-Bold').text('DESTINATION', 150, 214);
  doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text(dest.code || '—', 150, 224);

  try {
    const barcode = await bwipjs.toBuffer({ bcid: 'code128', text: childAWB, scale: 1.5, height: 8, includetext: false });
    doc.image(barcode, 20, 246, { width: 248, height: 36 });
  } catch {}

  doc.fillColor('#0f172a').fontSize(10).font('Helvetica-Bold').text(childAWB, 12, 290, { align: 'center', width: 264 });
  doc.fontSize(6).font('Helvetica').fillColor('#64748b').text('CHILD AWB', 12, 304, { align: 'center', width: 264 });

  doc.fillColor('#64748b').fontSize(5).text('Generated by Shipzy Railways', 8, 414, { align: 'center', width: 272 });
}
