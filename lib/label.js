import PDFDocument from 'pdfkit';
import bwipjs from 'bwip-js';
import { getShipments, getCustomers, getWarehouses } from './db';

export async function generateLabelPDF(shipmentId) {
  const shipments = await getShipments();
  const customers = await getCustomers();
  const warehouses = await getWarehouses();

  const shipment = shipments.find(s => s.id === shipmentId);
  if (!shipment) throw new Error('Shipment not found');

  const customer = customers.find(c => c.id === shipment.customerId) || {};
  const pickup = warehouses.find(w => w.id === shipment.pickupWarehouseId) || {};
  const delivery = warehouses.find(w => w.id === shipment.deliveryWarehouseId) || {};

  const doc = new PDFDocument({ size: [288, 432], margin: 6 });

  const buffers = [];
  doc.on('data', chunk => buffers.push(chunk));
  const pdfPromise = new Promise(resolve => doc.on('end', () => resolve(Buffer.concat(buffers))));

  for (let i = 0; i < (shipment.boxAWBs || []).length; i++) {
    if (i > 0) doc.addPage();
    await drawLabelPage(doc, {
      awb: shipment.boxAWBs[i],
      shipment,
      customer,
      pickup,
      delivery,
      boxIndex: i + 1,
      totalBoxes: shipment.boxAWBs.length,
    });
  }

  doc.end();
  return pdfPromise;
}

async function drawLabelPage(doc, { awb, shipment, customer, pickup, delivery, boxIndex, totalBoxes }) {
  // Header
  doc.rect(0, 0, 288, 32).fill('#0f172a');
  doc.fillColor('#ffffff').fontSize(10).font('Helvetica-Bold').text('SHIPZY RAILWAYS', 10, 10);
  doc.fontSize(7).font('Helvetica').text('4x6 Shipping Label', 190, 12, { align: 'right', width: 90 });

  // Top barcode
  try {
    const barcode = await bwipjs.toBuffer({ bcid: 'code128', text: awb, scale: 2, height: 14, includetext: false });
    doc.image(barcode, 16, 40, { width: 256 });
  } catch {}
  doc.fillColor('#0f172a').fontSize(11).font('Helvetica-Bold').text(awb, 16, 92, { align: 'center', width: 256 });

  // Shipping address box
  doc.rect(8, 108, 272, 72).stroke('#cbd5e1');
  doc.fontSize(7).font('Helvetica-Bold').fillColor('#0f172a').text('SHIPPING ADDRESS', 14, 114);
  doc.font('Helvetica').fontSize(9).text(customer.name || 'Consignee', 14, 126);
  doc.fontSize(7).text(delivery.address || '', 14, 138, { width: 180 });
  doc.text(`${delivery.city || ''} ${delivery.state || ''} - ${delivery.pin || ''}`, 14, 162);

  // PREPAID badge
  doc.rect(200, 114, 68, 16).fill('#10b981');
  doc.fillColor('#ffffff').fontSize(8).font('Helvetica-Bold').text('PREPAID', 210, 118);

  // Consignor section
  doc.fillColor('#0f172a').fontSize(7).font('Helvetica-Bold').text('CONSIGNOR', 14, 190);
  doc.font('Helvetica').fontSize(7).text(pickup.name || '', 14, 202);
  doc.text(pickup.address || '', 14, 212, { width: 150 });
  doc.text(`${pickup.city || ''} ${pickup.pin || ''}`, 14, 230);

  // Invoice details on right
  doc.fontSize(7).text(`Inv: ${shipment.invoiceNumber || 'N/A'}`, 180, 202);
  doc.text(`Amt: ${shipment.invoiceAmount || 0}`, 180, 212);
  doc.text(`Ins: ${shipment.insurance ? 'Yes' : 'No'}`, 180, 222);

  // Product box
  doc.rect(8, 248, 272, 36).fill('#f1f5f9');
  doc.fillColor('#0f172a').fontSize(7).font('Helvetica-Bold').text('PRODUCT', 14, 254);
  doc.font('Helvetica').fontSize(7).text(shipment.productDescription || 'General Cargo', 14, 266, { width: 160 });
  doc.fontSize(8).font('Helvetica-Bold').text(`Box ${boxIndex} / ${totalBoxes}`, 190, 258);

  // Bottom barcode
  try {
    const barcode2 = await bwipjs.toBuffer({ bcid: 'code128', text: awb, scale: 1.5, height: 10 });
    doc.image(barcode2, 24, 300, { width: 240 });
  } catch {}

  // Footer
  doc.fillColor('#64748b').fontSize(6).text('Generated by Shipzy Railways  \u2022  railway logistics', 8, 410, { align: 'center', width: 272 });
}
