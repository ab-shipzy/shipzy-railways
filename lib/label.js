import PDFDocument from 'pdfkit';
import bwipjs from 'bwip-js';
import { getShipments, getCustomers, getWarehouses } from './db';

export async function generateLabelPDF(shipmentId) {
  const shipments = await getShipments();
  const customers = await getCustomers();
  const warehouses = await getWarehouses();

  const shipment = shipments.find(s => s.id === shipmentId);
  if (!shipment) throw new Error('Shipment not found');

  const customer = customers.find(c => c.id === shipment.customerId) || {};
  const pickup = warehouses.find(w => w.id === shipment.pickupWarehouseId) || {};
  const delivery = warehouses.find(w => w.id === shipment.deliveryWarehouseId) || {};

  const doc = new PDFDocument({ size: [288, 432], margin: 8 });

  const buffers = [];
  doc.on('data', chunk => buffers.push(chunk));
  const pdfPromise = new Promise(resolve => doc.on('end', () => resolve(Buffer.concat(buffers))));

  for (let i = 0; i < (shipment.boxAWBs || []).length; i++) {
    if (i > 0) doc.addPage();
    await drawLabelPage(doc, {
      awb: shipment.boxAWBs[i],
      shipment,
      customer,
      pickup,
      delivery,
      boxIndex: i + 1,
      totalBoxes: shipment.boxAWBs.length,
    });
  }

  doc.end();
  return pdfPromise;
}

async function drawLabelPage(doc, { awb, shipment, customer, pickup, delivery, boxIndex, totalBoxes }) {
  doc.rect(0, 0, 288, 36).fill('#0f172a');
  doc.fillColor('#ffffff').fontSize(11).font('Helvetica-Bold').text('SHIPZY RAILWAYS', 12, 12);
  doc.fontSize(8).font('Helvetica').text('4x6 Shipping Label', 180, 16, { align: 'right', width: 96 });

  try {
    const barcode = await bwipjs.toBuffer({ bcid: 'code128', text: awb, scale: 2, height: 12, includetext: false });
    doc.image(barcode, 20, 44, { width: 248 });
  } catch {}
  doc.fillColor('#0f172a').fontSize(10).font('Helvetica-Bold').text(awb, 20, 92, { align: 'center', width: 248 });

  doc.rect(10, 110, 268, 70).stroke('#e2e8f0');
  doc.fontSize(8).font('Helvetica-Bold').text('SHIPPING ADDRESS', 16, 116);
  doc.font('Helvetica').fontSize(9).text(customer.name || 'Customer', 16, 128);
  doc.fontSize(7).text(delivery.address || '', 16, 140, { width: 250 });
  doc.text(`${delivery.city || ''} ${delivery.state || ''} - ${delivery.pin || ''}`, 16, 158);

  doc.rect(200, 116, 60, 18).fill('#10b981');
  doc.fillColor('#ffffff').fontSize(8).font('Helvetica-Bold').text('PREPAID', 208, 120);

  doc.fillColor('#0f172a').fontSize(8).font('Helvetica-Bold').text('FROM / SELLER', 16, 190);
  doc.font('Helvetica').fontSize(7).text(pickup.name || '', 16, 202);
  doc.text(pickup.address || '', 16, 212, { width: 160 });
  doc.text(`${pickup.city || ''} ${pickup.pin || ''}`, 16, 224);

  doc.fontSize(7).text(`Inv: ${shipment.invoiceNumber || 'N/A'}`, 180, 202);
  doc.text(`Amt: ${shipment.invoiceAmount || 0}`, 180, 212);
  doc.text(`Ins: ${shipment.insurance ? 'Yes' : 'No'}`, 180, 222);

  doc.rect(10, 240, 268, 40).fill('#f8fafc');
  doc.fillColor('#0f172a').fontSize(8).font('Helvetica-Bold').text('PRODUCT', 16, 246);
  doc.font('Helvetica').fontSize(7).text(shipment.productDescription || 'General Cargo', 16, 258, { width: 180 });
  doc.fontSize(8).font('Helvetica-Bold').text(`Box ${boxIndex} / ${totalBoxes}`, 180, 252);

  try {
    const barcode2 = await bwipjs.toBuffer({ bcid: 'code128', text: awb, scale: 1.4, height: 8 });
    doc.image(barcode2, 30, 290, { width: 228 });
  } catch {}

  doc.fillColor('#64748b').fontSize(6).text('Generated by Shipzy Railways  \u2022  railway logistics', 10, 410, { align: 'center', width: 268 });
}
