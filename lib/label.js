import PDFDocument from 'pdfkit';
import bwipjs from 'bwip-js';
import { getShipments, getWarehouses } from './db';

export async function generateLabelPDF(shipmentId) {
  const shipments = await getShipments();
  const warehouses = await getWarehouses();

  const shipment = shipments.find(s => s.id === shipmentId);
  if (!shipment) throw new Error('Shipment not found');

  // Customer is billing-only and is intentionally not printed on the label.
  const pickup = warehouses.find(w => w.id === shipment.pickupWarehouseId) || {};
  const delivery = warehouses.find(w => w.id === shipment.deliveryWarehouseId) || {};

  const doc = new PDFDocument({ size: [288, 432], margin: 8 });

  const buffers = [];
  doc.on('data', chunk => buffers.push(chunk));
  const pdfPromise = new Promise(resolve => doc.on('end', () => resolve(Buffer.concat(buffers))));

  const masterAWB = shipment.masterAWB || '';
  const boxAWBs = shipment.boxAWBs || [];

  for (let i = 0; i < boxAWBs.length; i++) {
    if (i > 0) doc.addPage();
    await drawLabelPage(doc, {
      childAWB: boxAWBs[i],
      masterAWB,
      shipment,
      pickup,
      delivery,
      boxIndex: i + 1,
      totalBoxes: boxAWBs.length,
    });
  }

  doc.end();
  return pdfPromise;
}

function formatAddress(w) {
  const lines = [];
  if (w.name) lines.push(w.name);
  if (w.address) lines.push(w.address);
  const cityLine = [w.city, w.state, w.pin].filter(Boolean).join(', ');
  if (cityLine) lines.push(cityLine);
  if (w.contact) lines.push(w.contact);
  return lines.join('\n');
}

async function drawLabelPage(doc, { childAWB, masterAWB, shipment, pickup, delivery, boxIndex, totalBoxes }) {
  doc.rect(0, 0, 288, 28).fill('#0f172a');
  doc.fillColor('#ffffff').fontSize(10).font('Helvetica-Bold').text('SHIPZY RAILWAYS', 10, 9);
  doc.fontSize(7).font('Helvetica').text('4x6 Shipping Label', 190, 11, { align: 'right', width: 90 });

  doc.fillColor('#0f172a').fontSize(8).font('Helvetica-Bold').text('MASTER AWB', 12, 38);
  doc.fontSize(13).font('Helvetica-Bold').text(masterAWB || '—', 12, 50);

  doc.rect(8, 74, 272, 78).stroke('#cbd5e1');
  doc.fontSize(7).font('Helvetica-Bold').text('SHIPPING ADDRESS', 14, 80);
  doc.font('Helvetica').fontSize(8).text(formatAddress(delivery) || 'Delivery warehouse not set', 14, 92, { width: 180, height: 54 });

  doc.rect(200, 80, 68, 16).fill('#10b981');
  doc.fillColor('#ffffff').fontSize(8).font('Helvetica-Bold').text('PREPAID', 210, 84);

  doc.fillColor('#0f172a').fontSize(7).font('Helvetica-Bold').text('CONSIGNOR', 14, 160);
  doc.font('Helvetica').fontSize(8).text(formatAddress(pickup) || 'Pickup warehouse not set', 14, 172, { width: 160, height: 40 });

  doc.fontSize(7).text(`Inv: ${shipment.invoiceNumber || 'N/A'}`, 180, 172);
  doc.text(`Amt: ${shipment.invoiceAmount || 0}`, 180, 182);
  doc.text(`Ins: ${shipment.insurance ? 'Yes' : 'No'}`, 180, 192);

  doc.rect(8, 218, 272, 32).fill('#f1f5f9');
  doc.fillColor('#0f172a').fontSize(7).font('Helvetica-Bold').text('PRODUCT', 14, 224);
  doc.font('Helvetica').fontSize(7).text(shipment.productDescription || 'General Cargo', 14, 236, { width: 160 });

  doc.rect(200, 222, 70, 22).fill('#0074ff');
  doc.fillColor('#ffffff').fontSize(11).font('Helvetica-Bold').text(`${boxIndex}/${totalBoxes}`, 200, 226, { align: 'center', width: 70 });

  try {
    const barcode = await bwipjs.toBuffer({ bcid: 'code128', text: childAWB, scale: 1.8, height: 12, includetext: false });
    doc.image(barcode, 24, 270, { width: 240 });
  } catch {}

  doc.fillColor('#0f172a').fontSize(11).font('Helvetica-Bold').text(childAWB, 24, 340, { align: 'center', width: 240 });
  doc.fontSize(7).font('Helvetica').text('CHILD AWB', 24, 356, { align: 'center', width: 240 });

  doc.fillColor('#64748b').fontSize(6).text('Generated by Shipzy Railways  \u2022  railway logistics', 8, 410, { align: 'center', width: 272 });
}
